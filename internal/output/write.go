// Package output writes generated documents to disk (or stdout) without
// clobbering files a human wrote.
package output

import (
	"bytes"
	"errors"
	"fmt"
	"os"
	"path/filepath"
	"strings"

	"github.com/avbel/claude-code-memory-takeout/internal/render"
)

// Status is how one Write call ended.
type Status string

const (
	StatusWritten  Status = "written"    // the file was created or replaced
	StatusUpToDate Status = "up to date" // identical bytes already on disk; not rewritten
	StatusStdout   Status = "stdout"     // content went to stdout, no file
)

// ErrExists marks an output file that was not generated by
// claude-code-memory-takeout; the CLI maps it to exit code 2.
var ErrExists = errors.New("output file is not generated by claude-code-memory-takeout")

// Write stores content at path. path "-" writes to os.Stdout and is done.
// An existing file with identical bytes is left alone (mtime preserved).
// An existing file whose first line is not the marker line (render.Marker)
// is an ErrExists error unless force is set. New or replaced files are
// written atomically: temp file in the same dir, sync, chmod 0644, rename.
func Write(path string, content []byte, force bool) (Status, error) {
	if path == "-" {
		if _, err := os.Stdout.Write(content); err != nil {
			return "", fmt.Errorf("write stdout: %w", err)
		}
		return StatusStdout, nil
	}

	existing, err := os.ReadFile(path)
	switch {
	case err == nil:
		// Identical output never rewrites, so repeated runs keep the mtime.
		// A checkout with CRLF line endings or a BOM is still "the same
		// file", so the comparison normalizes both away.
		if bytes.Equal(existing, content) || bytes.Equal(normalizeFile(existing), content) {
			return StatusUpToDate, nil
		}
		if !force && !hasMarker(existing) {
			return "", fmt.Errorf("%w: %s exists and was not generated by claude-code-memory-takeout; use --force", ErrExists, path)
		}
	case errors.Is(err, os.ErrNotExist):
		// New file: fall through to the write.
	default:
		return "", fmt.Errorf("read %s: %w", path, err)
	}

	if err := writeAtomic(path, content); err != nil {
		return "", err
	}
	return StatusWritten, nil
}

// hasMarker reports whether b starts with the marker line. A file holding
// only the marker, with no trailing newline, counts. A Windows checkout
// with autocrlf may hand the marker back with a trailing CR, and editors
// may add a BOM; both still count.
func hasMarker(b []byte) bool {
	first, _, _ := strings.Cut(string(b), "\n")
	return strings.TrimSuffix(strings.TrimPrefix(first, "\uFEFF"), "\r") == render.Marker
}

// normalizeFile strips a leading BOM and folds CRLF to LF, the form the
// tool writes.
func normalizeFile(b []byte) []byte {
	b = bytes.TrimPrefix(b, []byte("\uFEFF"))
	return bytes.ReplaceAll(b, []byte("\r\n"), []byte("\n"))
}

// writeAtomic writes content to a temp file beside path, then renames it into
// place so readers never observe a half-written document.
func writeAtomic(path string, content []byte) (err error) {
	tmp, err := os.CreateTemp(filepath.Dir(path), ".takeout-*")
	if err != nil {
		return fmt.Errorf("write %s: %w", path, err)
	}
	name := tmp.Name()
	defer func() {
		if err != nil {
			_ = tmp.Close()
			_ = os.Remove(name)
		}
	}()

	if _, err = tmp.Write(content); err != nil {
		return fmt.Errorf("write %s: %w", path, err)
	}
	if err = tmp.Sync(); err != nil {
		return fmt.Errorf("write %s: %w", path, err)
	}
	if err = tmp.Close(); err != nil {
		return fmt.Errorf("write %s: %w", path, err)
	}
	if err = os.Chmod(name, 0o644); err != nil {
		return fmt.Errorf("write %s: %w", path, err)
	}
	if err = os.Rename(name, path); err != nil {
		return fmt.Errorf("write %s: %w", path, err)
	}
	return nil
}
